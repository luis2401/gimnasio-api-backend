        CHECK (telefono ~ '^[0-9]{9}$'),

    CONSTRAINT ck_socio_nombre
        CHECK (btrim(nombre) <> ''),

    CONSTRAINT ck_socio_apellido
        CHECK (btrim(apellido) <> '')
);


-- ============================================================
-- 5. TABLA: plan_membresia
-- ============================================================

CREATE TABLE plan_membresia (
                                id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                nombre varchar(120) NOT NULL,
                                duracion_dias integer NOT NULL,

                                activo boolean NOT NULL DEFAULT true,

                                condiciones varchar(1000) NULL,

                                vigencia_desde date NULL,
                                vigencia_hasta date NULL,

                                CONSTRAINT uk_plan_membresia_nombre UNIQUE (nombre),

                                CONSTRAINT ck_plan_membresia_nombre
                                    CHECK (btrim(nombre) <> ''),

                                CONSTRAINT ck_plan_membresia_duracion
                                    CHECK (duracion_dias > 0),

                                CONSTRAINT ck_plan_membresia_vigencia
                                    CHECK (
                                        vigencia_hasta IS NULL
                                            OR vigencia_desde IS NULL
                                            OR vigencia_hasta >= vigencia_desde
                                        )
);


-- ============================================================
-- 6. TABLA: plan_sede
-- ============================================================

CREATE TABLE plan_sede (
                           id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                           plan_id integer NOT NULL,
                           sede_id integer NOT NULL,

                           precio_actual numeric(12,2) NOT NULL,
                           recargo_multisede numeric(12,2) NOT NULL DEFAULT 0,

                           activo boolean NOT NULL DEFAULT true,

                           CONSTRAINT uk_plan_sede
                               UNIQUE (plan_id, sede_id),

                           CONSTRAINT fk_plan_sede_plan
                               FOREIGN KEY (plan_id)
                                   REFERENCES plan_membresia (id),

                           CONSTRAINT fk_plan_sede_sede
                               FOREIGN KEY (sede_id)
                                   REFERENCES sede (id),

                           CONSTRAINT ck_plan_sede_precio
                               CHECK (precio_actual >= 0),

                           CONSTRAINT ck_plan_sede_recargo
                               CHECK (recargo_multisede >= 0)
);


-- ============================================================
-- 7. TABLA: usuario_sistema
-- ============================================================

CREATE TABLE usuario_sistema (
                                 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                 empleado_id integer NOT NULL,

                                 nombre_usuario varchar(40) NOT NULL,
                                 password_hash varchar(255) NOT NULL,

                                 activo boolean NOT NULL DEFAULT true,

                                 intentos_fallidos integer NOT NULL DEFAULT 0,

                                 bloqueado_hasta timestamptz NULL,
                                 ultimo_acceso timestamptz NULL,

                                 creado_en timestamptz NOT NULL DEFAULT current_timestamp,
                                 actualizado_en timestamptz NOT NULL DEFAULT current_timestamp,

                                 nivel_bloqueo integer NOT NULL DEFAULT 0,

                                 CONSTRAINT uk_usuario_sistema_empleado
                                     UNIQUE (empleado_id),

                                 CONSTRAINT uk_usuario_sistema_nombre
                                     UNIQUE (nombre_usuario),

                                 CONSTRAINT fk_usuario_sistema_empleado
                                     FOREIGN KEY (empleado_id)
                                         REFERENCES empleado (id),

                                 CONSTRAINT ck_usuario_sistema_nombre
                                     CHECK (btrim(nombre_usuario) <> ''),

                                 CONSTRAINT ck_usuario_sistema_intentos
                                     CHECK (intentos_fallidos >= 0),

                                 CONSTRAINT ck_usuario_sistema_nivel_bloqueo
                                     CHECK (nivel_bloqueo BETWEEN 0 AND 3)
);


