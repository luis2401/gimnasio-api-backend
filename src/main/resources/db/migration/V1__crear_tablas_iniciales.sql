CREATE TABLE asignacion_sede (
                                 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                 empleado_id integer NOT NULL,
                                 sede_id integer NOT NULL,

                                 fecha_desde date NOT NULL,
                                 fecha_hasta date NULL,

