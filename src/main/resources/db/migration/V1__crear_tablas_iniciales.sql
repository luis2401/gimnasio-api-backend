    ('SUPERVISOR', 'Supervisor'),
    ('INSTRUCTOR', 'Instructor'),
    ('RECEPCIONISTA', 'Recepcionista');


-- ============================================================
-- 2. TABLA: sede
-- ============================================================

CREATE TABLE sede (
                      id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      codigo varchar(30) NOT NULL,
                      nombre varchar(120) NOT NULL,
                      direccion varchar(250) NOT NULL,
                      activa boolean NOT NULL DEFAULT true,

                      CONSTRAINT uk_sede_codigo UNIQUE (codigo),
                      CONSTRAINT ck_sede_codigo_no_vacio CHECK (btrim(codigo) <> ''),
                      CONSTRAINT ck_sede_nombre_no_vacio CHECK (btrim(nombre) <> '')
);


-- ============================================================
-- 3. TABLA: empleado
-- ============================================================

CREATE TABLE empleado (
                          id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                          dni varchar(8) NOT NULL,
                          nombre varchar(80) NOT NULL,
                          apellido varchar(80) NOT NULL,

                          rol_id smallint NOT NULL,

                          activo boolean NOT NULL DEFAULT true,

                          telefono varchar(9) NOT NULL,
                          correo varchar(160) NULL,
                          direccion varchar(250) NULL,

                          especialidad varchar(120) NULL,

                          creado_en timestamptz NOT NULL DEFAULT current_timestamp,
                          actualizado_en timestamptz NOT NULL DEFAULT current_timestamp,

                          CONSTRAINT uk_empleado_dni UNIQUE (dni),

                          CONSTRAINT fk_empleado_rol
                              FOREIGN KEY (rol_id)
                                  REFERENCES rol (id),

                          CONSTRAINT ck_empleado_dni
                              CHECK (dni ~ '^[0-9]{8}$'),

    CONSTRAINT ck_empleado_telefono
        CHECK (telefono ~ '^[0-9]{9}$'),

    CONSTRAINT ck_empleado_nombre
        CHECK (btrim(nombre) <> ''),

    CONSTRAINT ck_empleado_apellido
        CHECK (btrim(apellido) <> '')
);


-- ============================================================
