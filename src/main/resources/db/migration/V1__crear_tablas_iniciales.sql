-- ============================================================
-- 10. TABLA: suscripcion
-- ============================================================
-- Guarda una fotografía de lo vendido en el momento de compra.
--
-- Por eso se mantienen:
-- nombre_plan_vendido
-- duracion_dias_vendida
-- precio_vendido
-- precio_lista
-- condiciones_vendidas
--
-- Aunque el plan cambie después, la suscripción conserva
-- exactamente lo que se vendió.
-- ============================================================

CREATE TABLE suscripcion (
                             id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                             socio_id integer NOT NULL,
                             plan_sede_id integer NOT NULL,

                             nombre_plan_vendido varchar(120) NOT NULL,
                             duracion_dias_vendida integer NOT NULL,

                             precio_vendido numeric(12,2) NOT NULL,
                             precio_lista numeric(12,2) NOT NULL,

                             condiciones_vendidas varchar(1000) NULL,

                             fecha_inicio date NOT NULL,
                             fecha_fin date NOT NULL,

                             estado varchar(30) NOT NULL DEFAULT 'ACTIVA',

                             creada_en timestamptz NOT NULL DEFAULT current_timestamp,

                             observacion_precio varchar(500) NULL,

                             acceso_multisede boolean NOT NULL DEFAULT false,
                             recargo_multisede numeric(12,2) NOT NULL DEFAULT 0,

                             CONSTRAINT fk_suscripcion_socio
                                 FOREIGN KEY (socio_id)
                                     REFERENCES socio (id),

                             CONSTRAINT fk_suscripcion_plan_sede
                                 FOREIGN KEY (plan_sede_id)
                                     REFERENCES plan_sede (id),

                             CONSTRAINT ck_suscripcion_duracion
                                 CHECK (duracion_dias_vendida > 0),

                             CONSTRAINT ck_suscripcion_precio_vendido
                                 CHECK (precio_vendido >= 0),

                             CONSTRAINT ck_suscripcion_precio_lista
                                 CHECK (precio_lista >= 0),

                             CONSTRAINT ck_suscripcion_recargo
                                 CHECK (recargo_multisede >= 0),

                             CONSTRAINT ck_suscripcion_fechas
                                 CHECK (fecha_fin >= fecha_inicio),

                             CONSTRAINT ck_suscripcion_estado
                                 CHECK (
                                     estado IN (
                                                'PENDIENTE',
                                                'ACTIVA',
                                                'VENCIDA',
                                                'CANCELADA',
                                                'SUSPENDIDA'
                                         )
                                     )
);


-- ============================================================
-- 11. TABLA: pago
-- ============================================================

CREATE TABLE pago (
                      id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                      fecha_pago timestamptz NOT NULL DEFAULT current_timestamp,

                      monto numeric(12,2) NOT NULL,

                      metodo varchar(30) NOT NULL,

                      suscripcion_id integer NULL,

                      sede_id integer NOT NULL,

                      vendedor_id integer NOT NULL,

                      numero_operacion varchar(48) NULL,

                      estado varchar(30) NOT NULL DEFAULT 'PAGADO',

                      motivo_anulacion varchar(500) NULL,

                      anulado_por integer NULL,

                      fecha_anulacion timestamptz NULL,

                      tipo_venta varchar(20) NOT NULL DEFAULT 'MEMBRESIA',

                      visitante_nombre varchar(120) NULL,
                      visitante_documento varchar(20) NULL,
                      fecha_acceso date NULL,

                      observacion_precio varchar(500) NULL,

                      CONSTRAINT fk_pago_sede
                          FOREIGN KEY (sede_id)
                              REFERENCES sede (id),

                      CONSTRAINT fk_pago_suscripcion
                          FOREIGN KEY (suscripcion_id)
                              REFERENCES suscripcion (id),

                      CONSTRAINT fk_pago_vendedor
                          FOREIGN KEY (vendedor_id)
                              REFERENCES empleado (id),

                      CONSTRAINT fk_pago_anulado_por
                          FOREIGN KEY (anulado_por)
                              REFERENCES empleado (id),

                      CONSTRAINT ck_pago_monto
                          CHECK (monto > 0),

                      CONSTRAINT ck_pago_metodo
                          CHECK (
                              metodo IN (
                                         'EFECTIVO',
                                         'YAPE',
                                         'PLIN',
                                         'TARJETA',
                                         'TRANSFERENCIA'
                                  )
                              ),

                      CONSTRAINT ck_pago_estado
                          CHECK (
                              estado IN (
                                         'PAGADO',
                                         'ANULADO'
                                  )
                              ),

                      CONSTRAINT ck_pago_tipo_venta
                          CHECK (
                              tipo_venta IN (
                                             'MEMBRESIA',
                                             'PASE_DIARIO'
                                  )
                              ),

    -- Reglas de origen de la venta
                      CONSTRAINT ck_pago_origen
                          CHECK (
                              (
                                  tipo_venta = 'MEMBRESIA'
                                      AND suscripcion_id IS NOT NULL
                                      AND visitante_nombre IS NULL
                                      AND fecha_acceso IS NULL
                                  )
                                  OR
                              (
                                  tipo_venta = 'PASE_DIARIO'
                                      AND suscripcion_id IS NULL
                                      AND visitante_nombre IS NOT NULL
                                      AND fecha_acceso IS NOT NULL
                                  )
                              ),

    -- Si el pago está anulado, debe existir información de anulación.
                      CONSTRAINT ck_pago_anulacion
                          CHECK (
                              (
                                  estado = 'PAGADO'
                                      AND anulado_por IS NULL
                                      AND fecha_anulacion IS NULL
                                  )
                                  OR
                              (
                                  estado = 'ANULADO'
                                      AND anulado_por IS NOT NULL
                                      AND fecha_anulacion IS NOT NULL
                                      AND motivo_anulacion IS NOT NULL
                                  )
                              )
);


-- ============================================================
-- 12. TABLA: clase
-- ============================================================

CREATE TABLE clase (
                       id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                       nombre varchar(120) NOT NULL,

                       dia_semana smallint NOT NULL,

                       hora_inicio time NOT NULL,
                       hora_fin time NOT NULL,

                       cupo_max integer NOT NULL,

                       activo boolean NOT NULL DEFAULT true,

                       instructor_id integer NOT NULL,
                       sede_id integer NOT NULL,

                       CONSTRAINT fk_clase_instructor
                           FOREIGN KEY (instructor_id)
                               REFERENCES empleado (id),

                       CONSTRAINT fk_clase_sede
                           FOREIGN KEY (sede_id)
                               REFERENCES sede (id),

                       CONSTRAINT ck_clase_nombre
                           CHECK (btrim(nombre) <> ''),

                       CONSTRAINT ck_clase_dia
                           CHECK (dia_semana BETWEEN 1 AND 7),

                       CONSTRAINT ck_clase_horario
                           CHECK (hora_fin > hora_inicio),

                       CONSTRAINT ck_clase_cupo
                           CHECK (cupo_max > 0)
);


-- ============================================================
-- 13. TABLA: socio_clase
-- ============================================================

CREATE TABLE socio_clase (
                             id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                             socio_id integer NOT NULL,
                             clase_id integer NOT NULL,

                             fecha_inscripcion date NOT NULL DEFAULT current_date,
                             fecha_baja date NULL,

                             activo boolean NOT NULL DEFAULT true,

                             CONSTRAINT fk_socio_clase_socio
                                 FOREIGN KEY (socio_id)
                                     REFERENCES socio (id),

                             CONSTRAINT fk_socio_clase_clase
                                 FOREIGN KEY (clase_id)
                                     REFERENCES clase (id),

                             CONSTRAINT ck_socio_clase_fechas
                                 CHECK (
                                     fecha_baja IS NULL
                                         OR fecha_baja >= fecha_inscripcion
                                     )
);


-- ============================================================
-- 14. TABLA: asistencia_clase
-- ============================================================

CREATE TABLE asistencia_clase (
                                  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                  socio_clase_id bigint NOT NULL,

                                  fecha date NOT NULL,

                                  estado varchar(20) NOT NULL,

                                  registrado_por integer NOT NULL,

                                  registrado_en timestamptz NOT NULL DEFAULT current_timestamp,

                                  observacion varchar(300) NULL,

                                  CONSTRAINT fk_asistencia_socio_clase
                                      FOREIGN KEY (socio_clase_id)
                                          REFERENCES socio_clase (id),

                                  CONSTRAINT fk_asistencia_registrado_por
                                      FOREIGN KEY (registrado_por)
                                          REFERENCES empleado (id),

                                  CONSTRAINT uk_asistencia_socio_clase_fecha
                                      UNIQUE (socio_clase_id, fecha),

                                  CONSTRAINT ck_asistencia_estado
                                      CHECK (
                                          estado IN (
                                                     'ASISTIO',
                                                     'FALTO',
                                                     'JUSTIFICADO'
                                              )
                                          )
);


