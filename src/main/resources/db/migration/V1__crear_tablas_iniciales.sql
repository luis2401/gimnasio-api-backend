                                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                usuario_id integer NOT NULL,

                                token_hash varchar(64) NOT NULL,

                                creada_en timestamptz NOT NULL DEFAULT current_timestamp,
                                expira_en timestamptz NOT NULL,

                                revocada_en timestamptz NULL,

                                CONSTRAINT uk_sesion_usuario_token
                                    UNIQUE (token_hash),

                                CONSTRAINT fk_sesion_usuario_usuario
                                    FOREIGN KEY (usuario_id)
                                        REFERENCES usuario_sistema (id),

                                CONSTRAINT ck_sesion_usuario_expiracion
                                    CHECK (expira_en > creada_en),

                                CONSTRAINT ck_sesion_usuario_revocacion
                                    CHECK (
                                        revocada_en IS NULL
                                            OR revocada_en >= creada_en
                                        )
);


